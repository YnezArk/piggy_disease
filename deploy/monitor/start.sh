#!/bin/bash
# ============================================================
# 猪咳嗽声智能监测服务 启动脚本
# 用法：容器入口（CMD）或宿主机直接执行：sh start.sh
# ============================================================
set -e
cd "$(dirname "$0")"
echo "=== 启动猪咳嗽声监测服务, port=${PORT:-8000} ==="
exec gunicorn -w 1 --threads 4 -b 0.0.0.0:${PORT:-8000} --timeout 600 app:app